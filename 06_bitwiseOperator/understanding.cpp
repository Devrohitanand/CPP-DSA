#include <iostream>
using namespace std;
int main (){

    cout << ( 1 & 1) <<endl;              // & ( using AND )
    return 0;
}

#include <iostream>
using namespace std;
int main (){

    cout << ( 1 | 1) <<endl;              // | ( using OR )
    return 0;
}

#include <iostream>
using namespace std;
int main (){

    cout << ( 1 ^ 1) <<endl;              // ^ ( using XOR )
    return 0;
}

